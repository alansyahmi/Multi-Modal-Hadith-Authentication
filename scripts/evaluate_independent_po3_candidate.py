"""Evaluate inductive OOF weakest-link scores against aligned hadith grades.

Only Abu Dawud, Tirmidhi, Nasai, and Ibn Majah rows from the local aligned
evaluation set are used. Bukhari and Muslim rows are excluded because the
dataset construction script assigned Sahih from collection membership rather
than an individually aligned grade.
"""
import ast
import json
import re
import unicodedata
import math
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr, kendalltau
from sklearn.metrics import accuracy_score, f1_score, confusion_matrix, mean_absolute_error

ROOT = Path(__file__).resolve().parent.parent
COHORT_DIR = ROOT / "output/corrected_candidate_20261029"
PREDICTIONS_PATH = ROOT / "output/corrected_candidate_20261029/inductive_po2/results.json"
EVAL_PATH = ROOT / "output/stage1/kutub_sitta_evaluation.csv"
ALIGNMENT_PATH = ROOT / "output/stage1/alignment_results.json"
SANADSET_PATH = ROOT / "Dataset/Sanadset 650K Data on Hadith Narrators/Sanadset 650K Data on Hadith Narrators/sanadset.csv"
OUT_PATH = ROOT / "output/corrected_candidate_20261029/po3_independent_candidate.json"


def normalize_arabic_name(text):
    text = unicodedata.normalize("NFKD", str(text))
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    text = text.replace("ـ", "").replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")
    text = text.replace("ى", "ي").replace("ة", "ه")
    return re.sub(r"\s+", " ", text).strip()


def normalize_matn(text):
    text = re.sub(r"[ً-ٌٍ-َّْٰٓ]", "", str(text))
    text = text.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")
    text = text.replace("ة", "ه").replace("ى", "ي")
    return re.sub(r"\s+", " ", text).strip()


def main():
    cohort = pd.read_csv(COHORT_DIR / "clean_narrators_cohort.csv")
    nodes = pd.read_csv(ROOT / "output/stage2/graph_nodes.csv")
    with open(PREDICTIONS_PATH, encoding="utf-8") as f:
        run = json.load(f)
    pred_ids = run["fold_predictions"]["P2-B (Inductive GCN concat)"]
    all_ids, all_preds = [], []
    for fold in pred_ids:
        all_ids.extend(fold["test_identity_ids"])
        all_preds.extend(fold["predicted_tiers"])
    pred_df = pd.DataFrame({"identity_id": all_ids, "pred": all_preds})
    pred_map = pred_df.groupby("identity_id")["pred"].agg(lambda x: int(x.mode().iloc[0])).to_dict()
    oracle_map = dict(zip(cohort["identity_id"].astype(int), cohort["tier_class"].astype(int)))

    raw_node_to_identity = {}
    for _, row in cohort.iterrows():
        for raw_id in str(row["graph_node_ids"]).split(","):
            raw_id = raw_id.strip()
            if raw_id:
                raw_node_to_identity[int(raw_id)] = int(row["identity_id"])
    name_to_identity = {
        str(r.canonical_name): raw_node_to_identity[int(r.node_id)]
        for r in nodes.itertuples()
        if int(r.node_id) in raw_node_to_identity
    }
    normalized_candidates = {}
    for name, identity in name_to_identity.items():
        normalized_candidates.setdefault(normalize_arabic_name(name), set()).add(identity)

    data = pd.read_csv(EVAL_PATH)
    with open(ALIGNMENT_PATH, encoding="utf-8") as f:
        alignment = json.load(f)
    # This alignment was generated by build_4_dataset_parameters_fast.py,
    # where corpus_idx is the raw SanadSet row index (chunk offset + row_idx).
    requested_corpus_indices = {int(item["corpus_idx"]) for item in alignment if item.get("is_match") and int(item["corpus_idx"]) >= 0}
    raw_corpus = {}
    raw_corpus_size = 0
    for chunk in pd.read_csv(SANADSET_PATH, usecols=["Matn", "Sanad"], chunksize=100_000, dtype_backend="pyarrow"):
        for matn, sanad in zip(chunk["Matn"], chunk["Sanad"]):
            if raw_corpus_size in requested_corpus_indices and not pd.isna(matn) and not pd.isna(sanad):
                raw_corpus[raw_corpus_size] = (str(sanad), normalize_matn(matn))
            raw_corpus_size += 1

    eligible_books = {"Sunan Abī Dāwūd", "Jāmiʿ at-Tirmiḏī", "Sunan al-Nasāʾī (al-Mujtabā)", "Sunan Ibn Mājah"}
    grade_map = {"Ṣaḥīḥ": 2, "Ḥasan": 1, "Ḍaʿīf": 0, "Mawḍūʿ": 0}
    aligned = []
    for item in alignment:
        if not item.get("is_match"):
            continue
        qi = int(item["query_idx"])
        if qi >= len(data):
            continue
        query = data.iloc[qi]
        if str(query.get("book_name")) not in eligible_books or query.get("grade_normalised") not in grade_map:
            continue
        ci = int(item["corpus_idx"])
        if ci in raw_corpus:
            aligned.append({"query_idx": qi, "corpus_idx": ci, "book": str(query["book_name"]), "grade": str(query["grade_normalised"]), "raw_grade": str(query["Grade"]), "tfidf_score": float(item.get("tfidf_score", 0)), "similarity_score": float(item.get("similarity_score", 0))})

    # One chain cannot be counted repeatedly. Conflicting grade assignments to
    # the same SanadSet row are quarantined; consistent duplicates keep the
    # best scored match.
    by_corpus = {}
    for item in aligned:
        by_corpus.setdefault(item["corpus_idx"], []).append(item)
    conflicting_duplicate_groups = [g for g in by_corpus.values() if len({x["grade"] for x in g}) > 1]
    conflicting_ids = {x["corpus_idx"] for g in conflicting_duplicate_groups for x in g}
    duplicate_groups = [g for g in by_corpus.values() if len(g) > 1 and g[0]["corpus_idx"] not in conflicting_ids]
    aligned_unique = [max(g, key=lambda x: (x["similarity_score"], x["tfidf_score"])) for g in by_corpus.values() if g[0]["corpus_idx"] not in conflicting_ids]
    y_true, y_pred, y_oracle, retained = [], [], [], []
    dropped_parse = dropped_coverage = 0
    normalized_only_matches = 0
    ambiguous_normalized_occurrences = 0
    for row in aligned_unique:
        try:
            chain = ast.literal_eval(raw_corpus[row["corpus_idx"]][0])
        except Exception:
            dropped_parse += 1
            continue
        identities = []
        for name in chain if isinstance(chain, list) else []:
            raw_name = str(name).strip()
            identity = name_to_identity.get(raw_name)
            if identity is None:
                candidates = normalized_candidates.get(normalize_arabic_name(raw_name), set())
                if len(candidates) == 1:
                    identity = next(iter(candidates))
                    normalized_only_matches += 1
                elif len(candidates) > 1:
                    ambiguous_normalized_occurrences += 1
            if identity is not None and identity in pred_map and (not identities or identities[-1] != identity):
                identities.append(identity)
        # Require two distinct matched narrators and a complete model score for
        # every matched cohort narrator in the observed chain segment.
        if len(set(identities)) < 2:
            dropped_coverage += 1
            continue
        y_true.append(grade_map[row["grade"]])
        y_pred.append(min(pred_map[i] for i in identities))
        y_oracle.append(min(oracle_map[i] for i in identities))
        query_row = data.iloc[row["query_idx"]]
        source_matn_norm = normalize_matn(query_row["Arabic_Text"])
        corpus_matn_norm = raw_corpus[row["corpus_idx"]][1]
        retained.append({"book": row["book"], "reference_grade": row["grade"], "raw_grade": row["raw_grade"], "cohort_narrators": len(identities), "corpus_idx": row["corpus_idx"], "query_idx": row["query_idx"], "tfidf_score": row["tfidf_score"], "partial_similarity_score": row["similarity_score"], "matched_matn_chars": len(corpus_matn_norm), "normalized_matn_exact_match": source_matn_norm == corpus_matn_norm, "source_reference": str(query_row.get("Reference", "")), "query_excerpt": str(query_row["Arabic_Text"])[:180], "matched_matn_excerpt": corpus_matn_norm[:180]})

    if not y_true:
        raise RuntimeError("No independently graded chains met the two-narrator coverage criterion")
    rho = spearmanr(y_true, y_pred)
    tau = kendalltau(y_true, y_pred)
    oracle_rho = spearmanr(y_true, y_oracle)
    oracle_tau = kendalltau(y_true, y_oracle)
    majority_class = int(pd.Series(y_true).mode().iloc[0])
    majority_pred = [majority_class] * len(y_true)
    payload = {
        "reference_provenance": "output/stage1/kutub_sitta_evaluation.csv joined by query_idx to output/stage1/alignment_results.json; corpus_idx interpreted as raw SanadSet row index, consistent with scripts/build_4_dataset_parameters_fast.py. Bukhari and Muslim excluded because their grades are assigned from collection membership.",
        "prediction_method": "majority vote over five outer-fold out-of-fold predictions per narrator from strict held-out-node inductive PO2 GCN; weakest-link aggregation over matched cohort narrators",
        "grade_mapping": grade_map,
        "n_source_queries": len(data), "n_eligible_aligned_rows_before_deduplication": len(aligned),
        "n_unique_sanadset_rows_after_deduplication": len(aligned_unique),
        "n_duplicate_match_groups_deduplicated": len(duplicate_groups),
        "n_conflicting_grade_duplicate_groups_quarantined": len(conflicting_duplicate_groups),
        "raw_sanadset_rows_reconstructed": raw_corpus_size,
        "retained_alignment_score_summary": pd.Series([r["tfidf_score"] for r in retained]).describe().to_dict(),
        "retained_matches_below_tfidf_0_5": sum(r["tfidf_score"] < 0.5 for r in retained),
        "retained_matn_length_summary": pd.Series([r["matched_matn_chars"] for r in retained]).describe().to_dict(),
        "retained_matches_with_matn_under_40_chars": sum(r["matched_matn_chars"] < 40 for r in retained),
        "retained_matches_with_matn_under_80_chars": sum(r["matched_matn_chars"] < 80 for r in retained),
        "retained_normalized_matn_exact_matches": sum(r["normalized_matn_exact_match"] for r in retained),
        "retained_raw_grade_counts": pd.Series([r["raw_grade"] for r in retained]).value_counts().head(30).to_dict(),
        "lowest_score_manual_review_examples": sorted(retained, key=lambda r: r["tfidf_score"])[:10],
        "n_evaluated_chains": len(y_true), "dropped_parse": dropped_parse, "dropped_insufficient_cohort_coverage": dropped_coverage,
        "unique_normalization_matches_used": normalized_only_matches,
        "ambiguous_normalized_name_occurrences_skipped": ambiguous_normalized_occurrences,
        "book_counts": pd.Series([r["book"] for r in retained]).value_counts().to_dict(),
        "reference_counts": pd.Series([grade_map[r["reference_grade"]] for r in retained]).value_counts().sort_index().to_dict(),
        "prediction_counts": pd.Series(y_pred).value_counts().sort_index().to_dict(),
        "exact_accuracy": float(accuracy_score(y_true, y_pred)),
        "macro_f1": float(f1_score(y_true, y_pred, labels=[0, 1, 2], average="macro", zero_division=0)),
        "mae": float(mean_absolute_error(y_true, y_pred)),
        "spearman_rho_descriptive": float(rho.statistic),
        "kendall_tau_descriptive": float(tau.statistic),
        "confusion_matrix_labels_0_1_2": confusion_matrix(y_true, y_pred, labels=[0, 1, 2]).tolist(),
        "reference_majority_baseline": {
            "predicted_class": majority_class,
            "exact_accuracy": float(accuracy_score(y_true, majority_pred)),
            "macro_f1": float(f1_score(y_true, majority_pred, labels=[0, 1, 2], average="macro", zero_division=0)),
        },
        "oracle_weakest_link_reference_comparison": {
            "exact_accuracy": float(accuracy_score(y_true, y_oracle)),
            "macro_f1": float(f1_score(y_true, y_oracle, labels=[0, 1, 2], average="macro", zero_division=0)),
            "mae": float(mean_absolute_error(y_true, y_oracle)),
            "spearman_rho_descriptive": float(oracle_rho.statistic),
            "kendall_tau_descriptive": float(oracle_tau.statistic),
        },
        "limitations": ["Evaluation is limited to aligned sample rows with at least two matched cohort narrators.", "The four retained book labels are external hadith grades, but grading provenance and alignment errors remain possible.", "Narrator predictions are majority-voted across five repeated CV seeds; chain records share narrators and are not independent, so inferential p-values are omitted."],
    }
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(payload, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
